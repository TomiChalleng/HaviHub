// every texture file the icons need (derived ones, "x#how", are made from these)
export function symbolTextures() {
  const out = new Set(['block/grass_block_top', 'block/grass_block_side', 'block/grass_block_side_overlay', 'item/potion', 'item/potion_overlay']);
  for (const s of MC_SYMBOLS) for (const t of s.flat ? [s.flat] : [s.top, s.front, s.side]) if (!t.includes('#')) out.add(t);
  return [...out];
}
