// Builds src/renderer/lib/mckeys.js: every vanilla key binding (Controls
// screen) with its default key and its official names, taken from Minecraft's
// own language files (en_us + es_cl of the newest release).
//   node scripts/mckeys/build.mjs <folder with en_us.json and es_cl.json>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = process.argv[2];
const en = JSON.parse(fs.readFileSync(path.join(dir, 'en_us.json'), 'utf8'));
const es = JSON.parse(fs.readFileSync(path.join(dir, 'es_cl.json'), 'utf8'));

// Controls screen order. def: default key ('' = Minecraft's own default, shown
// as "Predeterminada" because it is not listed here). since: first version.
const K = (k) => `key.keyboard.${k}`;
const LAYOUT = [
  ['movement', [['key.forward', K('w')], ['key.left', K('a')], ['key.back', K('s')], ['key.right', K('d')], ['key.jump', K('space')], ['key.sneak', K('left.shift')], ['key.sprint', K('left.control')]]],
  ['gameplay', [['key.attack', 'key.mouse.left'], ['key.use', 'key.mouse.right'], ['key.pickItem', 'key.mouse.middle']]],
  ['inventory', [['key.drop', K('q')], ...[1, 2, 3, 4, 5, 6, 7, 8, 9].map((n) => [`key.hotbar.${n}`, K(String(n))]), ['key.inventory', K('e')], ['key.swapOffhand', K('f')]]],
  ['creative', [['key.saveToolbarActivator', K('c')], ['key.loadToolbarActivator', K('x')]]],
  ['multiplayer', [['key.playerlist', K('tab')], ['key.chat', K('t')], ['key.command', K('slash')], ['key.socialInteractions', K('p')], ['key.friends', '', '26.3']]],
  ['misc', [['key.advancements', K('l')], ['key.quickActions', K('g'), '1.21.6'], ['key.screenshot', K('f2')], ['key.smoothCamera', K('unknown')], ['key.togglePerspective', K('f5')], ['key.toggleGui', K('f1'), '1.21.9'], ['key.fullscreen', K('f11')]]],
  ['spectator', [['key.spectatorOutlines', K('unknown')], ['key.spectatorHotbar', '', '1.21.9'], ['key.toggleSpectatorShaderEffects', '', '1.21.9']]],
  ['debug', []],
];
const debugKeys = Object.keys(en).filter((k) => k.startsWith('key.debug.')).sort((a, b) => (a === 'key.debug.overlay' ? -1 : b === 'key.debug.overlay' ? 1 : a === 'key.debug.modifier' ? -1 : b === 'key.debug.modifier' ? 1 : 0));
LAYOUT[LAYOUT.length - 1][1] = debugKeys.map((k) => [k, k === 'key.debug.overlay' || k === 'key.debug.modifier' ? K('f3') : '', '1.21.9']);

const catName = (lang, c) => lang[`key.category.minecraft.${c}`] || lang[`key.categories.${c}`] || c;
const CATEGORIES = LAYOUT.map(([c]) => ({ id: c, es: catName(es, c), en: catName(en, c) }));
const BINDS = [];
for (const [cat, list] of LAYOUT) {
  for (const [id, def, since] of list) {
    if (!en[id]) throw new Error(`unknown binding ${id}`);
    BINDS.push({ id, cat, def: def || '', es: es[id] || en[id], en: en[id], ...(since ? { since } : {}) });
  }
}
// every key in the lang files that the layout forgot
const known = new Set(BINDS.map((b) => b.id));
const forgot = Object.keys(en).filter((k) => /^key\.[a-zA-Z.0-9]+$/.test(k) && !/^key\.(keyboard|mouse|categories|category)\b/.test(k) && k !== 'key.mouse' && !known.has(k));
if (forgot.length) throw new Error(`missing in layout: ${forgot.join(', ')}`);

const keyNames = (lang) => Object.fromEntries(Object.entries(lang).filter(([k]) => /^key\.(keyboard|mouse)\./.test(k)));
const out = [
  '// Generated by scripts/mckeys/build.mjs from Minecraft 26.3 language files - do not edit.',
  `export const CATEGORIES = ${JSON.stringify(CATEGORIES)};`,
  `export const BINDS = ${JSON.stringify(BINDS, null, 0).replace(/\},\{/g, '},\n  {')};`,
  `export const KEY_NAMES = { es: ${JSON.stringify(keyNames(es))}, en: ${JSON.stringify(keyNames(en))} };`,
  `export const MOUSE_BUTTON = { es: ${JSON.stringify(es['key.mouse'])}, en: ${JSON.stringify(en['key.mouse'])} };`,
  '',
];
fs.writeFileSync(path.join(root, 'src/renderer/lib/mckeys.js'), out.join('\n'));
console.log(`${BINDS.length} bindings in ${CATEGORIES.length} categories`);
